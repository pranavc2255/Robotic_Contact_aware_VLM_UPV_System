"""Main-pipeline Qwen32 single-anchor contact-crop scoring backend.

This module is used by the main anchor-selection stage, not only by E3
experiment post-processing.

It uses the clean single-anchor contact crops already generated by
anchor_selection_stage.py:

    clean_single_anchor_inputs/source_A1.png ... source_A5.png

It sends each source anchor independently to the local Qwen server and ranks
anchors by physical contact usability.
"""

from __future__ import annotations

import csv
import json
import math
import re
import time
from pathlib import Path
from typing import Any
from urllib.error import HTTPError
from urllib.request import Request, urlopen


PROMPT_VERSION = "main_pipeline_qwen32_single_anchor_contact_score_v1"


PROMPT_TEMPLATE = """You are scoring one physical UPV contact anchor.

Source anchor ID: {anchor_id}

This is a physical UPV contact-affordance scoring task. Evaluate this ONE source anchor only. Do not compare it to other anchors.

The image shows two clean inspection crops side by side:
- Left panel = Top contact crop
- Right panel = Bottom contact crop

The full TOP crop and full BOTTOM crop are the inspection regions. The entire TOP crop is the intended top contact region. The entire BOTTOM crop is the intended bottom contact region. These are the exact regions where flat UPV transducers will touch.

Judge the full visible crop area in each panel. Do not rely on colored markers, UI decoration, or anchor order.

Each crop intentionally includes outside-of-object context beyond the edge. Inspect the edge boundary and the outside/background side near the edge. Defects may appear exactly at the edge or just outside the edge and still affect contact usability.

A good anchor requires BOTH TOP and BOTTOM strips to be clean, continuous, open, approximately planar, and stable for flat probe contact.

Penalize these visible contact risks in either crop:
- raised or attached material entering from the edge
- mortar-like crust or blobs
- vertical seam, crack, line, or material boundary crossing the crop
- abrupt color or texture change along the contact region suggesting mortar start, residue, attached material, chip, nonuniform surface, or unstable contact
- gray/white crust, mortar-like buildup, blobs, protrusions, debris, dust pile, nail, tape, splinter, or foreign object
- chipped, broken, jagged, missing, or non-planar contact edge
- visible non-planarity that would prevent stable flat probe contact

A candidate is usable only if BOTH top and bottom contact crops are usable. A candidate is poor if either TOP or BOTTOM crop is poor. If all anchors are imperfect, the downstream code will choose the least bad anchor from your independent scores.

Material awareness:
- Brick: normal red/brown/tan/beige/yellowish fired-clay texture, pores, speckles, dust, and roughness are not defects by themselves. Gray/white attached cement-like material, mortar, crust, protruding material, missing chip, jagged break, abrupt boundary, or debris inside the crop is a defect.
- Timber: normal grain, knots, color bands, and saw marks are not defects by themselves. Nails, screws, staples, tape, splinters, cracks, protruding chips, debris, or blocked strips are defects.
- Concrete/cinder block: normal gray cementitious texture, aggregate, pores, and roughness are not defects by themselves. Loose debris, protruding attached paste, broken/jagged edge, missing material, local obstruction, or material sticking out into the contact strip is a defect.

Scoring:
- 90-100: both strips are clean, continuous, planar, open, and clearly physically usable.
- 70-89: usable; only minor normal material texture or slight roughness; no obstruction.
- 40-69: questionable; minor contact uncertainty, limited visible support, nonuniformity, edge/corner/cutoff risk, or one side less reliable.
- 0-39: bad; blocked, chipped, debris-covered, mortar/crust/protrusion, broken/jagged, corner/cutoff-limited, or one side unusable.

Rules:
- If top_usable=false or bottom_usable=false, overall_usable should normally be false.
- If overall_usable=false, score should normally be below 40.
- If the image is uncertain, choose a lower score and explain the uncertainty.
- Do not give a generic reason; mention actual visible evidence.
- Return JSON only. Do not include markdown fences or text outside JSON.

Use exactly this compact JSON schema:
{{
  "anchor_id": "{anchor_id}",
  "top_defects": ["none"],
  "bottom_defects": ["none"],
  "top_usable": true,
  "bottom_usable": true,
  "overall_usable": true,
  "score": 0,
  "reason": "short physical-contact reason"
}}
"""


def _write_json(path: Path, payload: Any) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, default=str), encoding="utf-8")
    return str(path)


def _write_csv(path: Path, rows: list[dict[str, Any]], fields: list[str]) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    return str(path)


def _post_json(url: str, payload: dict[str, Any], timeout_sec: int) -> dict[str, Any]:
    data = json.dumps(payload).encode("utf-8")
    req = Request(url, data=data, headers={"Content-Type": "application/json"}, method="POST")
    try:
        with urlopen(req, timeout=float(timeout_sec)) as response:  # noqa: S310 - local server URL from config
            text = response.read().decode("utf-8", errors="replace")
    except HTTPError as exc:
        body = exc.read().decode("utf-8", errors="replace")[:2000]
        raise RuntimeError(f"Qwen HTTPError {exc.code}: {body}") from exc

    try:
        return json.loads(text)
    except Exception:
        return {"ok": False, "raw_http_text": text}


def _extract_json_object(raw: str) -> tuple[dict[str, Any] | None, str]:
    text = (raw or "").strip()
    text = re.sub(r"^```(?:json)?", "", text, flags=re.I).strip()
    text = re.sub(r"```$", "", text).strip()

    try:
        obj = json.loads(text)
        if isinstance(obj, dict):
            return obj, ""
    except Exception:
        pass

    s = text.find("{")
    e = text.rfind("}")
    if s >= 0 and e > s:
        try:
            obj = json.loads(text[s : e + 1])
            if isinstance(obj, dict):
                return obj, ""
        except Exception as exc:
            return None, str(exc)

    return None, "no JSON object found"


def _extract_response(response: dict[str, Any]) -> tuple[str, dict[str, Any] | None, bool, str]:
    raw = ""
    for key in ("text", "raw_text", "response", "output", "answer", "generated_text"):
        if isinstance(response.get(key), str):
            raw = str(response[key])
            break
    if not raw:
        raw = json.dumps(response, indent=2)

    parsed, err = _extract_json_object(raw)
    return raw, parsed, parsed is not None, err


def _as_bool(value: Any) -> bool | None:
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    if isinstance(value, str):
        s = value.strip().lower()
        if s in {"true", "1", "yes", "y", "usable", "good", "acceptable"}:
            return True
        if s in {"false", "0", "no", "n", "bad", "unusable"}:
            return False
    return None


def _safe_float(value: Any) -> float | None:
    try:
        if value is None or value == "":
            return None
        return float(value)
    except Exception:
        return None


def _string_list(value: Any) -> list[str]:
    if isinstance(value, list):
        out = [str(v).strip() for v in value if str(v).strip()]
        return out or ["none"]
    if value is None or value == "":
        return ["none"]
    return [str(value).strip()]


def _anchor_sort_key(anchor_id: str) -> tuple[int, str]:
    m = re.match(r"A(\d+)$", str(anchor_id))
    if m:
        return int(m.group(1)), str(anchor_id)
    return 10**9, str(anchor_id)


def _deterministic_feature_map(deterministic_features: dict[str, Any]) -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for item in deterministic_features.get("anchor_features", []) or []:
        if isinstance(item, dict) and item.get("anchor_id"):
            out[str(item["anchor_id"])] = item
    return out


def _normalize_response(parsed: dict[str, Any] | None, expected_anchor_id: str) -> tuple[dict[str, Any], bool, str]:
    if parsed is None:
        return {"anchor_id": expected_anchor_id, "parse_ok": False}, False, "missing parsed object"

    anchor_id = str(parsed.get("anchor_id") or expected_anchor_id).strip()
    if anchor_id != expected_anchor_id:
        return {
            "anchor_id": anchor_id,
            "expected_anchor_id": expected_anchor_id,
            "parse_ok": False,
            "raw_parsed": parsed,
        }, False, f"anchor_id mismatch: expected {expected_anchor_id}, got {anchor_id}"

    score = _safe_float(parsed.get("score"))
    top_usable = _as_bool(parsed.get("top_usable"))
    bottom_usable = _as_bool(parsed.get("bottom_usable"))
    overall_usable = _as_bool(parsed.get("overall_usable"))

    if score is None:
        return {
            "anchor_id": expected_anchor_id,
            "parse_ok": False,
            "raw_parsed": parsed,
        }, False, "missing numeric score"

    score = max(0.0, min(100.0, float(score)))

    if top_usable is None:
        top_usable = False
    if bottom_usable is None:
        bottom_usable = False
    if overall_usable is None:
        overall_usable = bool(top_usable and bottom_usable and score >= 70.0)

    norm = {
        "anchor_id": expected_anchor_id,
        "top_defects": _string_list(parsed.get("top_defects")),
        "bottom_defects": _string_list(parsed.get("bottom_defects")),
        "top_usable": bool(top_usable),
        "bottom_usable": bool(bottom_usable),
        "overall_usable": bool(overall_usable),
        "score": score,
        "reason": str(parsed.get("reason") or "").strip(),
        "parse_ok": True,
        "raw_parsed": parsed,
    }
    return norm, True, ""


def _rank_anchor_scores(
    source_ids: list[str],
    anchor_results: dict[str, dict[str, Any]],
    deterministic_features: dict[str, dict[str, Any]],
) -> list[str]:
    parsed_ids = [aid for aid in source_ids if anchor_results.get(aid, {}).get("parse_ok")]

    def key(aid: str) -> tuple[Any, ...]:
        r = anchor_results[aid]
        det = deterministic_features.get(aid, {})
        det_score = _safe_float(det.get("deterministic_score"))
        return (
            0 if bool(r.get("overall_usable")) else 1,
            -float(r.get("score") or -math.inf),
            -(det_score if det_score is not None else -math.inf),
            _anchor_sort_key(aid),
        )

    return sorted(parsed_ids, key=key)


def run_qwen32_single_anchor_contact_scoring(
    *,
    config: dict[str, Any],
    artifact_dir: str | Path,
    candidates: list[dict[str, Any]],
    deterministic_features: dict[str, Any],
    output_dir: str | Path,
    requested_material: str,
    axis_mode: str,
) -> dict[str, Any]:
    """Score each clean contact crop independently and return selected anchor."""

    cfg = config.get("anchor_selection", {}) or {}
    out = Path(output_dir)

    clean_dir = out / "clean_single_anchor_inputs"
    if not clean_dir.exists():
        return {
            "success": False,
            "failure_reason": f"missing clean_single_anchor_inputs directory: {clean_dir}",
            "selected_anchor_id": None,
        }

    source_ids = [str(c["anchor_id"]) for c in candidates]
    server_url = str(cfg.get("qwen_server_url") or cfg.get("server_url") or "http://127.0.0.1:8899").rstrip("/")
    endpoint = str(cfg.get("qwen_server_endpoint") or cfg.get("server_endpoint") or "/infer")
    infer_url = server_url + endpoint
    timeout_sec = int(cfg.get("qwen_timeout_sec", cfg.get("timeout_sec", 240)))
    max_new_tokens = int(cfg.get("qwen_single_anchor_max_new_tokens", cfg.get("max_new_tokens", 700)))
    temperature = float(cfg.get("qwen_temperature", 0.0))

    response_dir = out / "qwen32_single_anchor_responses"
    prompt_dir = out / "qwen32_single_anchor_prompts"
    parsed_dir = out / "qwen32_single_anchor_parsed"
    response_dir.mkdir(parents=True, exist_ok=True)
    prompt_dir.mkdir(parents=True, exist_ok=True)
    parsed_dir.mkdir(parents=True, exist_ok=True)

    deterministic_map = _deterministic_feature_map(deterministic_features)

    anchor_results: dict[str, dict[str, Any]] = {}
    rows: list[dict[str, Any]] = []

    for aid in source_ids:
        image_path = clean_dir / f"source_{aid}.png"
        prompt = PROMPT_TEMPLATE.format(anchor_id=aid)

        prompt_path = prompt_dir / f"source_{aid}_prompt.txt"
        prompt_path.write_text(prompt, encoding="utf-8")

        server_response_path = response_dir / f"source_{aid}_server_response.json"
        raw_path = response_dir / f"source_{aid}_raw.txt"
        parsed_path = parsed_dir / f"source_{aid}_parsed.json"

        if not image_path.exists():
            normalized = {
                "anchor_id": aid,
                "parse_ok": False,
                "parse_error": f"missing image: {image_path}",
                "score": "",
                "overall_usable": False,
                "top_usable": False,
                "bottom_usable": False,
                "top_defects": ["missing image"],
                "bottom_defects": ["missing image"],
                "reason": "",
            }
            anchor_results[aid] = normalized
        else:
            payload = {
                "image_path": str(image_path),
                "prompt_text": prompt,
                "prompt_version": PROMPT_VERSION,
                "max_new_tokens": max_new_tokens,
                "temperature": temperature,
                "output_path": str(raw_path),
            }

            t0 = time.perf_counter()
            response = _post_json(infer_url, payload, timeout_sec)
            elapsed_ms = round((time.perf_counter() - t0) * 1000.0, 3)
            _write_json(server_response_path, response)

            raw_text, parsed, parse_ok, parse_error = _extract_response(response)
            raw_path.write_text(raw_text or "", encoding="utf-8")

            normalized, norm_ok, norm_error = _normalize_response(parsed, aid)
            parse_ok = bool(parse_ok and norm_ok)
            final_error = "" if parse_ok else (norm_error or parse_error)

            normalized.update(
                {
                    "parse_ok": parse_ok,
                    "parse_error": final_error,
                    "elapsed_ms": elapsed_ms,
                    "rendered_input_path": str(image_path),
                    "raw_response_path": str(raw_path),
                    "parsed_response_path": str(parsed_path),
                    "server_response_path": str(server_response_path),
                    "prompt_path": str(prompt_path),
                }
            )
            anchor_results[aid] = normalized

        _write_json(parsed_path, anchor_results[aid])

        r = anchor_results[aid]
        rows.append(
            {
                "anchor_id": aid,
                "parse_ok": r.get("parse_ok", False),
                "score": r.get("score", ""),
                "overall_usable": r.get("overall_usable", ""),
                "top_usable": r.get("top_usable", ""),
                "bottom_usable": r.get("bottom_usable", ""),
                "top_defects": "; ".join(str(x) for x in r.get("top_defects", [])),
                "bottom_defects": "; ".join(str(x) for x in r.get("bottom_defects", [])),
                "reason": r.get("reason", ""),
                "parse_error": r.get("parse_error", ""),
                "rendered_input_path": r.get("rendered_input_path", str(image_path)),
                "raw_response_path": r.get("raw_response_path", str(raw_path)),
                "parsed_response_path": r.get("parsed_response_path", str(parsed_path)),
            }
        )

    score_table = out / "qwen32_single_anchor_score_table.csv"
    _write_csv(
        score_table,
        rows,
        [
            "anchor_id",
            "parse_ok",
            "score",
            "overall_usable",
            "top_usable",
            "bottom_usable",
            "top_defects",
            "bottom_defects",
            "reason",
            "parse_error",
            "rendered_input_path",
            "raw_response_path",
            "parsed_response_path",
        ],
    )

    ranked = _rank_anchor_scores(source_ids, anchor_results, deterministic_map)
    selected = ranked[0] if ranked else None

    result = {
        "success": bool(selected),
        "phase": "main_pipeline_qwen32_single_anchor_contact_scoring",
        "prompt_version": PROMPT_VERSION,
        "requested_material": requested_material,
        "axis_mode": axis_mode,
        "selected_anchor_id": selected,
        "selected_anchor": selected,
        "ranked_source_anchors": ranked,
        "anchors_attempted": len(source_ids),
        "anchors_parsed": sum(1 for r in anchor_results.values() if r.get("parse_ok")),
        "all_anchors_parsed": all(bool(r.get("parse_ok")) for r in anchor_results.values()),
        "final_selected_anchor_source": "qwen32_single_anchor_contact_scoring",
        "reasoning_short": anchor_results.get(selected or "", {}).get("reason", "") if selected else "",
        "anchor_results": anchor_results,
        "score_table_path": str(score_table),
        "qwen32_single_anchor_inputs_dir": str(clean_dir),
        "qwen32_single_anchor_response_dir": str(response_dir),
        "failure_reason": None if selected else "NO_PARSE_RESULT",
    }
    _write_json(out / "qwen32_single_anchor_decision.json", result)
    return result
